import { z } from 'zod';
import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { refsSchema, type MCPContent } from './shared.js';
import type { Store } from '../tasks.js';
import {
  handleGetByType,
  handleGetOverview,
  handleGetNext,
  handleGetAll,
  handleGetById,
  handleGetByScope,
  handleGetByExternalId,
  handleGetRelated,
  handleGetScopes,
  handleHealth,
} from './queryHandlers.js';
import {
  handleAdd,
  handleUpdate,
  handleReplace,
  handleUploadPlan,
  handleAddNote,
  handleUpdateNote,
  handleDeleteNote,
  handleSetStatus,
  handleDelete,
  handleUiStart,
  handleUiStop,
} from './mutationHandlers.js';

const NOTES_RULE = 'Notes are as authoritative as the description; on conflict the newest statement wins (a newer note overrides an older note, any note overrides the description). Use notes for decisions, findings and spec changes made after refinement — not as a scratchpad or progress log.';

const PARENT_ID_RULE = 'Optional id of the epic this task belongs to. Must point to a task of type "epic"; an epic itself cannot have a parent (no nesting) and a task belongs to at most one epic. Violations return an error.';

const statusParam = z.enum(['refinement', 'plan', 'todo', 'in_progress', 'done', 'open']).optional()
  .describe('Filter by status. Default: non-done. Pass "open" for refinement+plan+todo+in_progress, or a specific status (incl. "done") for exact match.');

export function registerTools(server: McpServer, store: Store): void {
  // ── add ────────────────────────────────────────────────────────────────────────
  const addSchema = {
    type: z.enum(['bug', 'feature', 'idea', 'tool', 'other', 'epic'])
      .describe('bug = defect to fix (highest priority class); feature = planned work that requires a /plan session before implementation; idea = exploratory thought, needs refinement before it becomes a feature; tool = developer-tooling improvement; other = anything that does not fit the above; epic = umbrella holding project context (goals, order, rules) for its child tasks — never implemented directly'),
    priority: z.enum(['low', 'medium', 'high', 'critical'])
      .describe('critical = blocking or data-loss risk, fix immediately; high = important, tackle soon; medium = normal backlog; low = nice-to-have'),
    title: z.string().min(1, 'Title must not be empty')
      .describe('Short, action-oriented title — start with a verb (e.g. "Fix undo animation glitch on session delete", "Add dark-mode toggle to settings")'),
    description: z.string().optional().default('')
      .describe('Full context the implementer will need: what is broken or needed, reproduction steps or acceptance criteria, relevant file paths, technical constraints. Be thorough — this is what the next session will read.'),
    scope: z.string().optional()
      .describe('Optional tool or area this task belongs to (e.g. "svg-path-joiner", "eink-frame", "task-manager"). Omit for project-wide tasks. Use getByScope to filter tasks by this value later.'),
    summary: z.string().optional()
      .describe('Short 2–3 line gist of the task (what it does, key decision, user-visible outcome). Generated by /refine before promotion to todo. Can be set manually here if known at creation time.'),
    plan: z.string().optional()
      .describe('Optional implementation plan in markdown. Written by the agent after /plan; read back via getById before /implement.'),
    refs: refsSchema
      .describe('Optional related-task references — use when this task depends on, blocks, or is otherwise connected to existing tasks. Each entry: { id: number, relation?: string }. Relation must be one of the canonical values; default "relates to". The server automatically writes the inverse on the referenced task — you only need to specify one side.'),
    status: z.enum(['refinement', 'plan', 'todo']).default('refinement')
      .describe('Initial status. ALWAYS leave as default "refinement" unless one of these holds: (a) the user explicitly told you to skip refinement / mark as todo, or (b) you just refined this exact task with the user in the current conversation. Otherwise pass "refinement" (or omit the field). Choosing "todo" without one of those conditions is a rule violation — when in doubt, pick "refinement".'),
    parentId: z.number().int().positive().optional()
      .describe(PARENT_ID_RULE),
    externalId: z.string().optional()
      .describe('External tracker ticket ID (JIRA/Asana/…, e.g. "OPXPIQ-6532"). Set it whenever the user names a ticket ID for this task. Find tasks by it later with getByExternalId.'),
  };
  server.tool(
    'add',
    'Schedule a new task — call this whenever the user reports a bug, requests a feature, shares an idea, or says "schedule" / "TODO" / "add to the list". Do NOT implement the task inline; add it and stop. New tasks ALWAYS default to status "refinement"; only pass status: "todo" when (a) the user explicitly asks to skip refinement, OR (b) the current conversation already refined this exact task with the user. When in doubt, omit status and let the next session run PM-style clarification. Returns { id } of the newly created task. Refs are auto-mirrored on the other side; no need for a separate update call. Refs pointing to nonexistent IDs or self-references are silently dropped.',
    addSchema,
    async (args: z.infer<z.ZodObject<typeof addSchema>>): Promise<MCPContent> => handleAdd(store, args)
  );

  // ── getByType ──────────────────────────────────────────────────────────────────
  const getByTypeSchema = {
    type: z.enum(['bug', 'feature', 'idea', 'tool', 'other', 'epic']).describe('Task type to filter: bug | feature | idea | tool | other | epic'),
    status: statusParam,
  };
  server.tool(
    'getByType',
    'Get tasks of a specific type — use for "show me all bugs", "list features", "what ideas do we have?". Filters by status. Default: non-done. Pass "open" for refinement+plan+todo+in_progress, or a single status (incl. "done") for exact match. Sorted by priority desc then id desc. When a task has a summary, description is omitted; tasks with notes show noteCount instead of the bodies — call getById for the full task.',
    getByTypeSchema,
    async (args: z.infer<z.ZodObject<typeof getByTypeSchema>>): Promise<MCPContent> => handleGetByType(store, args)
  );

  // ── getOverview ────────────────────────────────────────────────────────────────
  const getOverviewSchema = { status: statusParam };
  server.tool(
    'getOverview',
    'Get a count summary per type: refinement, plan, open (todo + in_progress), and done counts. Use for dashboard questions like "how many tasks are there?" or "give me a backlog summary". Filters by status. Default: non-done. Pass "open" for refinement+plan+todo+in_progress, or a single status (incl. "done") for exact match. Returns only types with at least one matching task, sorted by open count desc. Do NOT use this to answer "what\'s next?" — use getNext for that.',
    getOverviewSchema,
    async (args: z.infer<z.ZodObject<typeof getOverviewSchema>>): Promise<MCPContent> => handleGetOverview(store, args)
  );

  // ── getNext ────────────────────────────────────────────────────────────────────
  const getNextSchema = {
    type: z.enum(['bug', 'feature', 'idea', 'tool', 'other', 'epic']).optional()
      .describe('Narrow to one type (optional). Omit to recommend across all types using the bug > tool > feature > idea > other order. Epics are never returned, so "epic" always yields null.')
  };
  server.tool(
    'getNext',
    'Get the single next actionable task — use for "what should I do next?", "what\'s next?", or any recommendation request. Sort order: in_progress first (resume interrupted work), then refinement (needs PM clarification), then plan (awaiting plan write), then todo, then highest priority, then newest id (FILO). Considers refinement, plan, todo, and in_progress tasks. Never returns an epic — epics are context umbrellas, their children are the actionable work. Optional type filter narrows to one category. When no filter is given, apply the project prioritization order: bug > tool > feature > idea > other. IMPORTANT: if the returned task has status "refinement", do NOT start implementing — instead ask the user clarifying questions to refine the description, then promote to "todo" via setStatus. When a task has a summary, description is omitted; tasks with notes show noteCount instead of the bodies — call getById for the full task.',
    getNextSchema,
    async (args: z.infer<z.ZodObject<typeof getNextSchema>>): Promise<MCPContent> => handleGetNext(store, args)
  );

  // ── getAll ─────────────────────────────────────────────────────────────────────
  const getAllSchema = { status: statusParam };
  server.tool(
    'getAll',
    'Get tasks grouped by type — use for "show me everything", "list all tasks", "full backlog". Groups appear in type order: bug, feature, idea, tool, other, epic. Each group sorted by priority desc then id desc. Filters by status. Default: non-done. Pass "open" for refinement+plan+todo+in_progress, or a single status (incl. "done") for exact match. Prefer getNext for a single recommendation; prefer getByType when the user asks about one specific type. When a task has a summary, description is omitted; tasks with notes show noteCount instead of the bodies — call getById for the full task.',
    getAllSchema,
    async (args: z.infer<z.ZodObject<typeof getAllSchema>>): Promise<MCPContent> => handleGetAll(store, args)
  );

  // ── getById ────────────────────────────────────────────────────────────────────
  const getByIdSchema = { id: z.coerce.number().int().positive().describe('The numeric task ID to look up') };
  server.tool(
    'getById',
    'Get a single task by its numeric ID — returns the full task including both summary (if set) and description, plus notes (oldest first) when the task has any, and refs as { id, relation, title } so you can tell what each linked task is without fetching it. A task in an epic also carries `epic` { id, title, status, summary, description, notes } — the epic\'s full text and notes, authoritative context for the child (order, goals, rules). An epic carries `children` [{ id, title, status, type, priority }] ordered by id. List methods carry only parentId + epicTitle. Other list methods omit description when summary is present and show only noteCount — use this when you need the full body. Notes are as authoritative as the description; newest statement wins on conflict. Use when the user asks about a specific task by number (e.g. "show me #42", "what is task 37?"). Returns an error listing valid IDs if not found.',
    getByIdSchema,
    async (args: z.infer<z.ZodObject<typeof getByIdSchema>>): Promise<MCPContent> => handleGetById(store, args)
  );

  // ── setStatus ──────────────────────────────────────────────────────────────────
  const setStatusSchema = {
    id: z.coerce.number().int().positive().describe('Task ID — get it from getNext, getAll, getByType, or getById'),
    status: z.enum(['refinement', 'plan', 'todo', 'in_progress', 'done']).describe('refinement = needs PM clarification before work starts; plan = planning in progress (opt-in step between refinement and todo); todo = ready to implement; in_progress = actively being worked on (set this before beginning); done = completed and committed (set this after user confirms the commit)')
  };
  server.tool(
    'setStatus',
    'Update a task\'s status. Lifecycle rules: always call setStatus(in_progress) before starting work on a task; always call setStatus(done) after the commit is made and the user confirms. Returns { success: true } — plus knowledgeReminder on done, and epicStatus when the task\'s epic moved (epic status follows its children automatically) — or { error }.',
    setStatusSchema,
    async (args: z.infer<z.ZodObject<typeof setStatusSchema>>): Promise<MCPContent> => handleSetStatus(store, args)
  );

  // ── update ────────────────────────────────────────────────────────────────────
  const updateSchema = {
    id: z.coerce.number().int().positive().describe('Task ID to update — get it from getNext, getAll, getById, etc.'),
    title: z.string().min(1).optional().describe('New title (replaces current). Start with a verb.'),
    description: z.string().optional().describe('New description (replaces current). Include full context: what, why, acceptance criteria, file paths.'),
    priority: z.enum(['low', 'medium', 'high', 'critical']).optional().describe('New priority: critical = blocking; high = important soon; medium = normal; low = nice-to-have'),
    type: z.enum(['bug', 'feature', 'idea', 'tool', 'other', 'epic']).optional().describe('New type — use to reclassify a task (e.g. idea → feature after refinement). An epic with children cannot be retyped.'),
    scope: z.string().nullable().optional().describe('New scope tag (e.g. "eink-frame"), or null to clear the scope entirely'),
    externalId: z.string().nullable().optional().describe('New external tracker ticket ID (JIRA/Asana/…, e.g. "OPXPIQ-6532"), or null / empty string to clear it'),
    summary: z.string().nullable().optional()
      .describe('Short 2–3 line summary of the task. Pass null or empty string to clear it. Should capture: what the task does, the most important decision, and the user-visible outcome.'),
    plan: z.string().nullable().optional()
      .describe('New plan content (markdown). Pass null or empty string to clear. For plans saved in a .md file, prefer uploadPlan.'),
    refs: refsSchema.nullable()
      .describe('Full replacement list of related-task references, or null / empty array to clear all refs. Each entry: { id, relation? } where relation is one of the canonical values. Defaults to "relates to". The server automatically updates the inverse on each referenced task — only specify one side. This replaces the existing refs list entirely — include all refs you want to keep.'),
    parentId: z.number().int().positive().nullable().optional()
      .describe(`${PARENT_ID_RULE} Pass null to detach the task from its epic.`),
  };
  server.tool(
    'update',
    'Patch any fields of an existing task in place — use when the user asks to edit, rename, reprioritize, retype, rescope, or update the refs/description of a task. Only the fields you provide are changed; omitted fields keep their current values. Returns { success: true, task } with the updated task (plan and note bodies omitted, noteCount instead — use getById), or { success: false, error }. Refs pointing to nonexistent IDs or self-references are silently dropped.',
    updateSchema,
    async (args: z.infer<z.ZodObject<typeof updateSchema>>): Promise<MCPContent> => handleUpdate(store, args)
  );

  // ── replace ────────────────────────────────────────────────────────────────────
  const replaceSchema = {
    id: z.coerce.number().int().positive().describe('Task ID to edit'),
    field: z.enum(['description', 'plan']).default('description').describe('Which field to edit. Default: description.'),
    anchor: z.string().min(1).describe('Exact snippet to find — case- and whitespace-sensitive, no regex. Must occur exactly once in the field; extend it with surrounding text if it is not unique.'),
    replace_with: z.string().describe('Text to put in place of the anchor. Empty string deletes the anchor.'),
  };
  server.tool(
    'replace',
    'Surgical edit of a task\'s description or plan: swaps one exact, unique snippet for new text without re-sending the whole field. Prefer over update for small edits. The anchor must match exactly once — 0 matches or 2+ matches return an error (with the count) and nothing is written. Returns a slim { success, id, field } without the task body — call getById if you need to see the result.',
    replaceSchema,
    async (args: z.infer<z.ZodObject<typeof replaceSchema>>): Promise<MCPContent> => handleReplace(store, args)
  );

  // ── uploadPlan ─────────────────────────────────────────────────────────────────
  const uploadPlanSchema = {
    id: z.coerce.number().int().positive().describe('Task ID to store the plan on'),
    path: z.string().min(1).describe('Absolute path to a .md file inside the project root (folder of TASKS_DB), ~/.claude/plans/, or the OS temp dir'),
  };
  server.tool(
    'uploadPlan',
    "Store a markdown file as a task's plan. The server reads the file, so you don't paste plan text into update(). Use this whenever the plan already exists as a .md file (e.g. the plan-mode file). Re-uploading replaces the stored plan; the DB copy is canonical and the file is left on disk. Only files under the project root (folder of TASKS_DB), ~/.claude/plans/ or the OS temp dir are accepted; symlinks are resolved before the check. Returns { success, id, bytes }; read the plan back with getById.",
    uploadPlanSchema,
    async (args: z.infer<z.ZodObject<typeof uploadPlanSchema>>): Promise<MCPContent> => handleUploadPlan(store, args)
  );

  // ── addNote ────────────────────────────────────────────────────────────────────
  const addNoteSchema = {
    taskId: z.coerce.number().int().positive().describe('Task ID to attach the note to'),
    body: z.string().min(1).describe('Note text. Must not be empty or whitespace-only.'),
  };
  server.tool(
    'addNote',
    `Append a note to a task without re-sending the description. Prefer this over update({ description }) for incremental additions. ${NOTES_RULE} Bumps the task's updated_at. Returns { success, note }.`,
    addNoteSchema,
    async (args: z.infer<z.ZodObject<typeof addNoteSchema>>): Promise<MCPContent> => handleAddNote(store, args)
  );

  // ── updateNote ─────────────────────────────────────────────────────────────────
  const updateNoteSchema = {
    noteId: z.coerce.number().int().positive().describe('Note ID — from the notes array returned by getById'),
    body: z.string().min(1).describe('Replacement note text. Must not be empty or whitespace-only.'),
  };
  server.tool(
    'updateNote',
    `Replace the body of an existing note. ${NOTES_RULE} Bumps the parent task's updated_at. Returns { success, note }.`,
    updateNoteSchema,
    async (args: z.infer<z.ZodObject<typeof updateNoteSchema>>): Promise<MCPContent> => handleUpdateNote(store, args)
  );

  // ── deleteNote ─────────────────────────────────────────────────────────────────
  const deleteNoteSchema = {
    noteId: z.coerce.number().int().positive().describe('Note ID to remove'),
  };
  server.tool(
    'deleteNote',
    "Permanently remove a note — e.g. after /refine has folded it into the description. Bumps the parent task's updated_at. Returns { success }.",
    deleteNoteSchema,
    async (args: z.infer<z.ZodObject<typeof deleteNoteSchema>>): Promise<MCPContent> => handleDeleteNote(store, args)
  );

  // ── getByScope ────────────────────────────────────────────────────────────────
  const getByScopeSchema = {
    scope: z.string().describe('Exact scope value to filter by (e.g. "svg-path-joiner"). Must match exactly — scope is case-sensitive.'),
    status: statusParam,
  };
  server.tool(
    'getByScope',
    'Get tasks tagged with a specific scope — use when the user asks "what tasks are there for svg-path-joiner?" or "show me everything related to eink-frame". Filters by status. Default: non-done. Pass "open" for refinement+plan+todo+in_progress, or a single status (incl. "done") for exact match. Sorted by priority desc then id desc. Scope values are set via add or update. Empty results may indicate a wrong/typo\'d scope; use getScopes to discover valid values. When a task has a summary, description is omitted; tasks with notes show noteCount instead of the bodies — call getById for the full task.',
    getByScopeSchema,
    async (args: z.infer<z.ZodObject<typeof getByScopeSchema>>): Promise<MCPContent> => handleGetByScope(store, args)
  );

  // ── getByExternalId ───────────────────────────────────────────────────────────
  const getByExternalIdSchema = {
    externalId: z.string().min(1).describe('External tracker ticket ID to look up (e.g. "OPXPIQ-6532")'),
  };
  server.tool(
    'getByExternalId',
    'Find tasks by external tracker ticket ID — call this first whenever the user asks about a JIRA/Asana/other ticket ID (e.g. "what is the status of OPXPIQ-6532?"). Case-insensitive exact match across all statuses, including done. Returns { externalId, tasks } — an array, since several tasks (e.g. an epic and its children) may share one ID; sorted by id; empty when none match. When a task has a summary, description is omitted — call getById for the full task.',
    getByExternalIdSchema,
    async (args: z.infer<z.ZodObject<typeof getByExternalIdSchema>>): Promise<MCPContent> => handleGetByExternalId(store, args)
  );

  // ── getRelated ────────────────────────────────────────────────────────────────
  const getRelatedSchema = {
    id: z.coerce.number().int().positive().describe('Task ID to find related tasks for'),
    status: statusParam,
  };
  server.tool(
    'getRelated',
    'Get tasks related to a given task — returns the task itself, outbound (tasks that #X references, decorated with refRelation), and inbound (tasks that reference #X). Filters by status. Default: non-done. Pass "open" for refinement+plan+todo+in_progress, or a single status (incl. "done") for exact match. Every entry, the anchor included, is list mode: summary when present, description otherwise; no plan; noteCount instead of note bodies. Call getById for the full task.',
    getRelatedSchema,
    async (args: z.infer<z.ZodObject<typeof getRelatedSchema>>): Promise<MCPContent> => handleGetRelated(store, args)
  );

  // ── getScopes ─────────────────────────────────────────────────────────────────
  server.tool(
    'getScopes',
    'List all scopes that exist across active and done tasks — use to discover valid scope values before calling getByScope or getByStatus with a scope filter. Returns { scopes: Array<{ scope, total, open }> }. Sorted: open desc, then total desc, then alphabetically.',
    {},
    async (): Promise<MCPContent> => handleGetScopes(store)
  );

  // ── health ────────────────────────────────────────────────────────────────────
  server.tool(
    'health',
    'Validate the task-manager setup AND report the UI URL. Checks .mcp.json config, probes the UI port, and verifies DB migrations. Returns a human-readable health report with ✓/⚠/✗ status lines, actionable fix instructions, and the localhost + LAN-IP URLs for the task-manager UI. Call this when the user asks where the UI is, asks for the link, or wants the URL to open the task-manager in their browser — the LAN URL in the Runtime section is the clickable address.',
    {},
    async (): Promise<MCPContent> => handleHealth()
  );

  // ── delete ────────────────────────────────────────────────────────────────────
  const deleteSchema = { id: z.coerce.number().int().positive().describe('The numeric task ID to permanently remove') };
  server.tool(
    'delete',
    'Permanently remove a task from the database. Use ONLY when the user explicitly asks to delete, remove, drop, or cancel a task — not when work is finished (use setStatus(done) for that). Cascade-removes refs from/to this task and its notes. This is irreversible.',
    deleteSchema,
    async (args: z.infer<z.ZodObject<typeof deleteSchema>>): Promise<MCPContent> => handleDelete(store, args)
  );

  // ── ui-start ──────────────────────────────────────────────────────────────────
  server.tool(
    'ui-start',
    'Start the task-manager-ui if not already running. Idempotent — returns alreadyRunning if the port is already in use. Respects TASK_UI_DISABLE.',
    {},
    async (): Promise<MCPContent> => handleUiStart()
  );

  // ── ui-stop ───────────────────────────────────────────────────────────────────
  server.tool(
    'ui-stop',
    'Stop the task-manager-ui if running and owned by this MCP process. No-op if already down. Returns a warning if the UI is running but was started externally.',
    {},
    async (): Promise<MCPContent> => handleUiStop()
  );
}
