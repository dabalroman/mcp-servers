import { z } from 'zod';
import type { McpServer } from '@modelcontextprotocol/sdk/server/mcp.js';
import { refsSchema, prsSchema, projectParam, withSchemaCheck, type MCPContent, type SessionContext } from './shared.js';
import type { Store } from '../tasks.js';
import {
  handleGetOverview,
  handleGetNext,
  handleGetAll,
  handleGetById,
  handleGetByExternalId,
  handleGetByPr,
  handleGetUpdates,
  handleGetRelated,
  handleGetScopes,
  handleGetProjects,
  handleHealth,
} from './queryHandlers.js';
import {
  handleAdd,
  handleUpdate,
  handleReplace,
  handleAddNote,
  handleUpdateNote,
  handleDeleteNote,
  handleSetStatus,
  handleDelete,
  handleCreateProject,
  handleUpdateProject,
  handleUiStart,
  handleUiStop,
} from './mutationHandlers.js';

const PARENT_ID_RULE = 'Optional id of the epic this task belongs to. Must point to a task of type "epic"; an epic itself cannot have a parent (no nesting) and a task belongs to at most one epic. Violations return an error.';

const statusParam = z.enum(['refinement', 'plan', 'todo', 'in_progress', 'done', 'open']).optional()
  .describe('Filter by status. Default: non-done. Pass "open" for refinement+plan+todo+in_progress, or a specific status (incl. "done") for exact match.');

export function registerTools(server: McpServer, store: Store, ctx: SessionContext): void {
  // ── add ────────────────────────────────────────────────────────────────────────
  const addSchema = {
    type: z.enum(['bug', 'feature', 'idea', 'tool', 'other', 'epic'])
      .describe('bug = defect to fix (highest priority class); feature = planned work; goes through refinement, a plan is opt-in; idea = exploratory thought, needs refinement before it becomes a feature; tool = developer-tooling improvement; other = anything that does not fit the above; epic = umbrella holding project context (goals, order, rules) for its child tasks — never implemented directly'),
    priority: z.enum(['low', 'medium', 'high', 'critical'])
      .describe('critical = blocking or data-loss risk, fix immediately; high = important, tackle soon; medium = normal backlog; low = nice-to-have'),
    title: z.string().min(1, 'Title must not be empty')
      .describe('Short, action-oriented title — start with a verb (e.g. "Fix undo animation glitch on session delete", "Add dark-mode toggle to settings")'),
    description: z.string().optional().default('')
      .describe('Full context the implementer will need: what is broken or needed, reproduction steps or acceptance criteria, relevant file paths, technical constraints. Be thorough — this is what the next session will read.'),
    scope: z.string().optional()
      .describe('Optional tool or area this task belongs to (e.g. "svg-path-joiner", "eink-frame", "task-manager"). Omit for project-wide tasks. Filter by it later with getAll({ scope }). A child of an epic always inherits the epic\'s scope; a passed scope is ignored then.'),
    summary: z.string().optional()
      .describe('Short 2–3 line gist of the task (what it does, key decision, user-visible outcome). Generated by /tm:refine before promotion to todo. Can be set manually here if known at creation time.'),
    plan: z.string().optional()
      .describe('Optional implementation plan in markdown. Written by the agent after /plan; read back via getById before /tm:implement. Must be plain UTF-8 text (no control characters); a BOM is stripped and CRLF is stored as LF.'),
    refs: refsSchema
      .describe('Optional related-task references (depends on, blocks, …). Each entry: { id, relation? }, relation one of the canonical values (default "relates to"). The inverse is written automatically — specify one side only. Nonexistent ids and self-references are silently dropped; a task from another project is rejected.'),
    status: z.enum(['refinement', 'plan', 'todo']).default('refinement')
      .describe('Initial status. ALWAYS leave as default "refinement" unless one of these holds: (a) the user explicitly told you to skip refinement / mark as todo, or (b) you just refined this exact task with the user in the current conversation. Otherwise pass "refinement" (or omit the field). Choosing "todo" without one of those conditions is a rule violation — when in doubt, pick "refinement".'),
    parentId: z.number().int().positive().optional()
      .describe(PARENT_ID_RULE),
    externalId: z.string().optional()
      .describe('External tracker ticket ID (JIRA/Asana/…, e.g. "OPXPIQ-6532"). Set it whenever the user names a ticket ID for this task. Find tasks by it later with getByExternalId.'),
    prs: prsSchema
      .describe('Pull/merge requests of this task: { url, number, status: draft|open|pipeline_pass|approved|merged|deployed|closed }, url http(s) and unique per task. Works in every project, whether or not it tracks PRs.'),
    project: projectParam,
  };
  server.tool(
    'add',
    'Schedule a new task — call this whenever the user reports a bug, requests a feature, shares an idea, or says "schedule" / "TODO" / "add to the list". Do NOT implement the task inline; add it and stop. Status defaults to "refinement" — see status. Returns { id }. Refs pointing to nonexistent IDs or self-references are silently dropped.',
    addSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof addSchema>>): Promise<MCPContent> => handleAdd(store, args, ctx))
  );

  // ── getOverview ────────────────────────────────────────────────────────────────
  const getOverviewSchema = { status: statusParam, project: projectParam };
  server.tool(
    'getOverview',
    'Get a count summary per type: refinement, plan, open (todo + in_progress), and done counts. Use for dashboard questions like "how many tasks are there?" or "give me a backlog summary". Returns only types with at least one matching task, sorted by open count desc. Do NOT use this to answer "what\'s next?" — use getNext for that.',
    getOverviewSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof getOverviewSchema>>): Promise<MCPContent> => handleGetOverview(store, args, ctx))
  );

  // ── getNext ────────────────────────────────────────────────────────────────────
  const getNextSchema = {
    type: z.enum(['bug', 'feature', 'idea', 'tool', 'other', 'epic']).optional()
      .describe('Narrow to one type (optional). Omit to consider all types. "epic" always yields null.'),
    project: projectParam,
  };
  server.tool(
    'getNext',
    'Get the single next actionable task — use for "what should I do next?", "what\'s next?", or any recommendation request. Sort order: in_progress first (resume interrupted work), then refinement, then plan, then todo, then highest priority, then newest id (FILO). With no type filter the type order is bug > tool > feature > idea > other. Never returns an epic — its children are the actionable work.',
    getNextSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof getNextSchema>>): Promise<MCPContent> => handleGetNext(store, args, ctx))
  );

  // ── getAll ─────────────────────────────────────────────────────────────────────
  const getAllSchema = {
    status: statusParam,
    type: z.enum(['bug', 'feature', 'idea', 'tool', 'other', 'epic']).optional().describe('Only this type (optional).'),
    scope: z.string().optional().describe('Only this scope (optional) — exact, case-sensitive. An empty result may be a typo; see getScopes.'),
    project: projectParam,
  };
  server.tool(
    'getAll',
    'List tasks grouped by type — use for "show me everything", "all bugs", "what is open in auth?". Optional type and scope filters narrow the list; the shape is always { tasks: { <type>: [...] } }, groups in type order (bug, feature, idea, tool, other, epic), empty groups dropped, each sorted by priority desc then id desc. Prefer getNext for a single recommendation.',
    getAllSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof getAllSchema>>): Promise<MCPContent> => handleGetAll(store, args, ctx))
  );

  // ── getById ────────────────────────────────────────────────────────────────────
  const getByIdSchema = { id: z.coerce.number().int().positive().describe('The numeric task ID to look up') };
  server.tool(
    'getById',
    'Get a single task by its numeric ID — returns the full task including both summary (if set) and description, plus notes (oldest first) when the task has any, and refs as { id, relation, title } so you can tell what each linked task is without fetching it. A task in an epic also carries `epic` { id, title, status, summary, description, notes } — the epic\'s full text and notes, authoritative context for the child (order, goals, rules). An epic carries `children` [{ id, title, status, type, priority }] ordered by id. List methods carry only parentId + epicTitle. List tools omit description when a summary is present and show only noteCount, so use this for the full body. Use when the user asks about a specific task by number (e.g. "show me #42", "what is task 37?"). Returns an error listing valid IDs if not found.',
    getByIdSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof getByIdSchema>>): Promise<MCPContent> => handleGetById(store, args))
  );

  // ── setStatus ──────────────────────────────────────────────────────────────────
  const setStatusSchema = {
    id: z.coerce.number().int().positive().describe('Task ID — get it from getNext, getAll, or getById'),
    status: z.enum(['refinement', 'plan', 'todo', 'in_progress', 'done']).describe('refinement = needs PM clarification before work starts; plan = planning in progress (opt-in step between refinement and todo); todo = ready to implement; in_progress = actively being worked on (set this before beginning); done = completed and committed (set this after user confirms the commit)')
  };
  server.tool(
    'setStatus',
    'Update a task\'s status. Returns { success: true } — plus knowledgeReminder on done, and epicStatus when the task\'s epic moved (epic status follows its children automatically) — or { error }.',
    setStatusSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof setStatusSchema>>): Promise<MCPContent> => handleSetStatus(store, args))
  );

  // ── update ────────────────────────────────────────────────────────────────────
  const updateSchema = {
    id: z.coerce.number().int().positive().describe('Task ID to update — get it from getNext, getAll, getById, etc.'),
    title: z.string().min(1).optional().describe('New title (replaces current). Start with a verb.'),
    description: z.string().optional().describe('New description (replaces current).'),
    priority: z.enum(['low', 'medium', 'high', 'critical']).optional().describe('New priority (see add for the scale)'),
    type: z.enum(['bug', 'feature', 'idea', 'tool', 'other', 'epic']).optional().describe('New type — use to reclassify a task (e.g. idea → feature after refinement). An epic with children cannot be retyped.'),
    scope: z.string().nullable().optional().describe('New scope tag (e.g. "eink-frame"), or null to clear the scope entirely. Ignored for a child of an epic, which always has the epic\'s scope; rescoping an epic rescopes its children.'),
    externalId: z.string().nullable().optional().describe('New external tracker ticket ID (JIRA/Asana/…, e.g. "OPXPIQ-6532"), or null / empty string to clear it'),
    summary: z.string().nullable().optional()
      .describe('Short 2–3 line gist. Pass null or empty string to clear it.'),
    plan: z.string().nullable().optional()
      .describe('New plan content (markdown) — this is how a plan is stored. Pass null or empty string to clear. For small edits use replace(). Must be plain UTF-8 text (no control characters); a BOM is stripped and CRLF is stored as LF.'),
    refs: refsSchema.nullable()
      .describe('Full replacement list of related-task references, or null / empty array to clear all. Each entry: { id, relation? }, relation one of the canonical values (default "relates to"). The inverse is written automatically — specify one side only. Replaces the existing list entirely — include every ref you want to keep. Nonexistent ids and self-references are silently dropped; a newly added task from another project is rejected.'),
    prs: prsSchema.nullable()
      .describe('Full replacement list of the task\'s pull/merge requests ({ url, number, status: draft|open|pipeline_pass|approved|merged|deployed|closed }), or null / empty array to clear. Include every PR you want to keep; to change a status, resend the list with the new status. Works in every project, whether or not it tracks PRs.'),
    parentId: z.number().int().positive().nullable().optional()
      .describe(`${PARENT_ID_RULE} Pass null to detach the task from its epic.`),
    project: z.string().min(1).optional()
      .describe('Move the task to this project id. Must already exist (see getProjects). Omit to keep its current project.'),
  };
  server.tool(
    'update',
    'Patch any fields of an existing task in place — use when the user asks to edit, rename, reprioritize, retype, rescope, move to another project, or update the refs/description of a task. Omitted fields keep their current values. Returns { success: true, task } (plan and note bodies omitted, noteCount instead — use getById), or { success: false, error }.',
    updateSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof updateSchema>>): Promise<MCPContent> => handleUpdate(store, args))
  );

  // ── replace ────────────────────────────────────────────────────────────────────
  const replaceSchema = {
    id: z.coerce.number().int().positive().describe('Task ID to edit'),
    field: z.enum(['description', 'plan']).default('description').describe('Which field to edit. Default: description.'),
    anchor: z.string().min(1).describe('Exact snippet to find — case- and whitespace-sensitive, no regex. Must occur exactly once in the field; extend it with surrounding text if it is not unique.'),
    replace_with: z.string().describe('Text to put in place of the anchor. Empty string deletes the anchor.'),
  };
  server.tool(
    'replace',
    'Surgical edit of a task\'s description or plan: swaps one exact, unique snippet for new text without re-sending the whole field. Prefer over update for small edits. The anchor must match exactly once — 0 matches or 2+ matches return an error (with the count) and nothing is written. Returns a slim { success, id, field } without the task body — call getById if you need to see the result.',
    replaceSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof replaceSchema>>): Promise<MCPContent> => handleReplace(store, args))
  );

  // ── addNote ────────────────────────────────────────────────────────────────────
  const addNoteSchema = {
    taskId: z.coerce.number().int().positive().describe('Task ID to attach the note to'),
    body: z.string().min(1).describe('Note text. Must not be empty or whitespace-only.'),
  };
  server.tool(
    'addNote',
    "Append a note to a task without re-sending the description. Prefer this over update({ description }) for incremental additions. Returns { success, note }.",
    addNoteSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof addNoteSchema>>): Promise<MCPContent> => handleAddNote(store, args))
  );

  // ── updateNote ─────────────────────────────────────────────────────────────────
  const updateNoteSchema = {
    noteId: z.coerce.number().int().positive().describe('Note ID — from the notes array returned by getById'),
    body: z.string().min(1).describe('Replacement note text. Must not be empty or whitespace-only.'),
  };
  server.tool(
    'updateNote',
    'Replace the body of an existing note. Returns { success, note }.',
    updateNoteSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof updateNoteSchema>>): Promise<MCPContent> => handleUpdateNote(store, args))
  );

  // ── deleteNote ─────────────────────────────────────────────────────────────────
  const deleteNoteSchema = {
    noteId: z.coerce.number().int().positive().describe('Note ID to remove'),
  };
  server.tool(
    'deleteNote',
    "Permanently remove a note. Returns { success }.",
    deleteNoteSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof deleteNoteSchema>>): Promise<MCPContent> => handleDeleteNote(store, args))
  );

  // ── getByExternalId ───────────────────────────────────────────────────────────
  const getByExternalIdSchema = {
    externalId: z.string().min(1).describe('External tracker ticket ID to look up (e.g. "OPXPIQ-6532")'),
  };
  server.tool(
    'getByExternalId',
    'Find tasks by external tracker ticket ID — call this first whenever the user asks about a JIRA/Asana/other ticket ID (e.g. "what is the status of OPXPIQ-6532?"). Case-insensitive exact match across all statuses, including done. Returns { externalId, tasks } — an array, since several tasks (e.g. an epic and its children) may share one ID; sorted by id; empty when none match.',
    getByExternalIdSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof getByExternalIdSchema>>): Promise<MCPContent> => handleGetByExternalId(store, args))
  );

  // ── getByPr ───────────────────────────────────────────────────────────────────
  const getByPrSchema = {
    url: z.string().min(1).optional().describe('PR/MR url (GitHub .../pull/N or GitLab .../-/merge_requests/N). Suffixes like /files, query and #fragment are ignored.'),
    repo: z.string().min(1).optional().describe('Repository as owner/name (GitLab: group/subgroup/name), case-insensitive. Use together with number instead of url.'),
    number: z.coerce.number().int().positive().optional().describe('PR/MR number. Use together with repo instead of url.'),
  };
  server.tool(
    'getByPr',
    'Find the tasks that track a pull/merge request — call this whenever you handle a PR event or a PR url/number the user names. Pass url, or repo + number. Searches all statuses (done included) and all projects. Returns { pr, tasks } — pr is the parsed { host?, repo, number }; tasks are list entries (with prs) sorted by id, each with a slim epic { id, title, status, summary? } when it belongs to one; empty when none match.',
    getByPrSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof getByPrSchema>>): Promise<MCPContent> => handleGetByPr(store, args))
  );

  // ── getUpdates ────────────────────────────────────────────────────────────────
  const getUpdatesSchema = {
    since: z.union([z.string().min(1), z.number()])
      .describe('Only tasks updated at or after this instant (inclusive). ISO 8601, SQLite \'YYYY-MM-DD HH:MM:SS\' (UTC), or epoch seconds/ms (number or numeric string). Pass the asOf from your previous getUpdates call to poll for the next batch.'),
    ids: z.array(z.number().int().positive()).optional().describe('Only these task ids (optional). ORed with epicId when both are given; omit both to poll the whole project/scope.'),
    epicId: z.number().int().positive().optional().describe('Only this epic and its children (optional). ORed with ids when both are given.'),
    scope: z.string().optional().describe('Only this scope (optional), ANDed with ids/epicId.'),
    project: projectParam,
  };
  server.tool(
    'getUpdates',
    'Poll for tasks changed since a timestamp; use this instead of re-calling getById/getAll to check whether a watched task or epic changed. Every status is included (no type/status filter), so a task moving to done is reported; filters are ANDed except ids/epicId which are ORed together. Returns { asOf, tasks, missing? }: asOf is the server\'s current time: store it and pass it as `since` on your next call. tasks are list-shaped (see getAll) plus a `notes` array of only the notes added or edited since `since` (omitted when none). missing lists requested ids/epicId that no longer exist (deleted), omitted when empty. Dedupe on (id, updated_at) across polls: several edits between polls collapse into one entry, and a same-second write can appear in two consecutive polls.',
    getUpdatesSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof getUpdatesSchema>>): Promise<MCPContent> => handleGetUpdates(store, args, ctx))
  );

  // ── getRelated ────────────────────────────────────────────────────────────────
  const getRelatedSchema = {
    id: z.coerce.number().int().positive().describe('Task ID to find related tasks for'),
    status: statusParam,
  };
  server.tool(
    'getRelated',
    'Get tasks related to a given task — returns the task itself, outbound (tasks that #X references, decorated with refRelation), and inbound (tasks that reference #X). Every entry, the anchor included, is shaped like a list entry (see getById).',
    getRelatedSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof getRelatedSchema>>): Promise<MCPContent> => handleGetRelated(store, args))
  );

  // ── getScopes ─────────────────────────────────────────────────────────────────
  const getScopesSchema = { project: projectParam };
  server.tool(
    'getScopes',
    'List all scopes that exist across active and done tasks of one project — use to discover valid scope values before filtering getAll by scope. Returns { project, scopes: Array<{ scope, total, open }> }. Sorted: open desc, then total desc, then alphabetically.',
    getScopesSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof getScopesSchema>>): Promise<MCPContent> => handleGetScopes(store, args, ctx))
  );

  // ── getProjects ───────────────────────────────────────────────────────────────
  server.tool(
    'getProjects',
    "List all projects with task counts — use when the user asks which projects exist, or before passing `project` to another tool. Every task belongs to exactly one project; list tools default to this session's project (PROJECT_NAME). Task IDs are global, so getById, getRelated, setStatus and notes work across projects. Returns { boundProject, projects: Array<{ id, name, total, open, trackPrs }> } sorted by name; pass `id` as `project` (name is display only); open = not done; trackPrs = agents in it are expected to record PRs.",
    {},
    withSchemaCheck(store, async (): Promise<MCPContent> => handleGetProjects(store, ctx))
  );

  // ── createProject ─────────────────────────────────────────────────────────────
  const createProjectSchema = {
    name: z.string().min(1).describe('Display name, 1–64 characters. The id is derived from it.'),
  };
  server.tool(
    'createProject',
    'Create a new, empty project. Only call this when the user asks for a new project — never to make an unknown `project` argument work. The id is derived from the name (lowercase, a–z, 0–9 and \'-\', e.g. "Random Tools" → random-tools) and never changes. Returns { success, project: { id, name } }, or an error if that id is already taken.',
    createProjectSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof createProjectSchema>>): Promise<MCPContent> => handleCreateProject(store, args))
  );

  // ── updateProject ─────────────────────────────────────────────────────────────
  const updateProjectSchema = {
    project: z.string().min(1).describe('Id of the project to change (case-insensitive).'),
    trackPrs: z.boolean().describe('true adds an instruction telling agents in this project to record the PRs/MRs they open. It does not enable the prs field: prs on add/update works in every project either way. Takes effect from the next session.'),
  };
  server.tool(
    'updateProject',
    'Change a project\'s settings. Only call when the user asks for this setting (e.g. "turn on PR tracking"), never to make another tool or field work. Returns { success, project: { id, name, trackPrs } }, or an error for an unknown project.',
    updateProjectSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof updateProjectSchema>>): Promise<MCPContent> => handleUpdateProject(store, args))
  );

  // ── health ────────────────────────────────────────────────────────────────────
  server.tool(
    'health',
    'Validate the task-manager setup AND report the UI URL. Checks the bound project, .mcp.json config, probes the UI port, and verifies DB migrations. Returns a human-readable health report with ✓/⚠/✗ status lines, actionable fix instructions, and the localhost + LAN-IP URLs for the task-manager UI. Call this when the user asks where the UI is, asks for the link, or wants the URL to open the task-manager in their browser — the LAN URL in the Runtime section is the clickable address.',
    {},
    withSchemaCheck(store, async (): Promise<MCPContent> => handleHealth({ store, ctx }))
  );

  // ── delete ────────────────────────────────────────────────────────────────────
  const deleteSchema = { id: z.coerce.number().int().positive().describe('The numeric task ID to permanently remove') };
  server.tool(
    'delete',
    'Permanently remove a task from the database. Use ONLY when the user explicitly asks to delete, remove, drop, or cancel a task — not when work is finished (use setStatus(done) for that). Cascade-removes refs from/to this task and its notes. This is irreversible.',
    deleteSchema,
    withSchemaCheck(store, async (args: z.infer<z.ZodObject<typeof deleteSchema>>): Promise<MCPContent> => handleDelete(store, args))
  );

  // Over HTTP this process is the UI itself; pm2/child answers would mislead.
  if (ctx.transport === 'http') return;

  // ── ui-start ──────────────────────────────────────────────────────────────────
  server.tool(
    'ui-start',
    'Start the task-manager-ui if not already running. Idempotent — returns alreadyRunning if the port is already in use.',
    {},
    withSchemaCheck(store, async (): Promise<MCPContent> => handleUiStart())
  );

  // ── ui-stop ───────────────────────────────────────────────────────────────────
  server.tool(
    'ui-stop',
    'Stop the task-manager-ui if running and owned by this MCP process. No-op if already down. Returns a warning if the UI is running but was started externally.',
    {},
    withSchemaCheck(store, async (): Promise<MCPContent> => handleUiStop())
  );
}
