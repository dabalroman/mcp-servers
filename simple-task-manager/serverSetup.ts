/**
 * install.ts --server on|off: runs the server (the UI + /mcp) as a long-lived pm2 app.
 *
 * One server serves every project on its DB, as the pm2 app `task-manager`
 * (`task-manager-<port>` on a non-default port). The dir holding
 * ecosystem.task-ui.config.cjs owns it. The server never touches `.mcp.json`:
 * repos connect to it in client mode (UI → Connect a machine).
 */
import { readFileSync, writeFileSync, existsSync, unlinkSync } from 'node:fs';
import { resolve } from 'node:path';
import { execFileSync } from 'node:child_process';
import { pm2AppName } from './mcpConfig.js';
import { PACKAGE_DIR } from './packageDir.js';

const UI_CWD = resolve(PACKAGE_DIR, 'task-manager-ui');
export const ECOSYSTEM_FILE = 'ecosystem.task-ui.config.cjs';

// The filename MUST include `.config.`: pm2 only treats a file as an ecosystem
// config when its name matches that pattern; otherwise it runs the file as a
// script and ignores apps[].name.
export function ecosystemFile(o: { appName: string; uiCwd: string; db: string; port: string }): string {
  return `// Generated by install.ts --server on. Re-run it to regenerate.
module.exports = {
  apps: [{
    name: ${JSON.stringify(o.appName)},
    script: 'server.ts',
    interpreter: 'node',
    interpreter_args: '--import tsx',
    cwd: ${JSON.stringify(o.uiCwd)},
    env: {
      TASKS_DB: ${JSON.stringify(o.db)},
      TASK_UI_PORT: ${JSON.stringify(o.port)},
    },
  }],
};
`;
}

function pm2(args: string[], { ignoreFailure = false }: { ignoreFailure?: boolean } = {}): void {
  try {
    execFileSync('pm2', args, { stdio: 'inherit', shell: process.platform === 'win32' });
  } catch (err) {
    if (!ignoreFailure) throw err;
  }
}

// UI apps on this port registered under older per-repo names (PROJECT_NAME). Matched
// by script path and port, never by name, so an unrelated pm2 app that shares a
// project's name survives, and so does a UI on another port.
function legacyUiApps(name: string, port: string): string[] {
  try {
    type App = { name: string; pm2_env?: { pm_exec_path?: string; TASK_UI_PORT?: string } };
    const apps = JSON.parse(execFileSync('pm2', ['jlist'], { encoding: 'utf8', shell: process.platform === 'win32' })) as App[];
    const script = resolve(UI_CWD, 'server.ts');
    return apps
      .filter((a) => a.name !== name && a.pm2_env?.pm_exec_path === script && (a.pm2_env.TASK_UI_PORT ?? '7374') === port)
      .map((a) => a.name);
  } catch {
    return [];
  }
}

async function uiAnswersOn(port: string): Promise<boolean> {
  try {
    const res = await fetch(`http://localhost:${port}/api/config`, { signal: AbortSignal.timeout(2000) });
    return res.ok && typeof ((await res.json()) as { mode?: unknown }).mode === 'string';
  } catch {
    return false;
  }
}

export async function runServerSetup(o: { action: 'on' | 'off'; dir: string; db?: string; port?: string }): Promise<void> {
  const port = o.port ?? '7374';
  const appName = pm2AppName(port);
  const file = resolve(o.dir, ECOSYSTEM_FILE);
  const connect = 'Connect each repo in client mode: open the UI, click Connect a machine, run the line it prints in the repo.';

  if (o.action === 'on') {
    const db = o.db ? resolve(o.db) : resolve(o.dir, 'tasks.db');
    if (!existsSync(file) && await uiAnswersOn(port)) {
      console.log(`\nA task-manager server already answers on port ${port}; nothing to start.`);
      console.log(connect);
      return;
    }
    writeFileSync(file, ecosystemFile({ appName, uiCwd: UI_CWD, db, port }));
    // Replace the previous registration (and any old per-repo UI app), then start fresh.
    for (const name of [appName, ...legacyUiApps(appName, port)]) pm2(['delete', name], { ignoreFailure: true });
    pm2(['start', file]);
    pm2(['save']);
    console.log(`\nServer started as pm2 app "${appName}" on port ${port} (db: ${db}).`);
    console.log(connect);
    return;
  }

  if (existsSync(file)) {
    // Without --port, stop the app this file started rather than the default one.
    const owned = o.port ?? /TASK_UI_PORT: "(\d+)"/.exec(readFileSync(file, 'utf8'))?.[1] ?? port;
    const appName = pm2AppName(owned);
    for (const name of [appName, ...legacyUiApps(appName, owned)]) pm2(['delete', name], { ignoreFailure: true });
    pm2(['save'], { ignoreFailure: true });
    unlinkSync(file);
    console.log(`\nServer "${appName}" removed. Client-mode repos lose their task-manager until they bind elsewhere.`);
  } else {
    console.log(`\n${o.dir} doesn't own a server (no ${ECOSYSTEM_FILE}); nothing removed.`);
  }
}
